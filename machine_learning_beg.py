def build_vocabulary(corpus):
    '''
    Builds a sorted list of unique words from all documents in the corpus.
    '''
    vocab_set = set()

    for doc in corpus:
        cleaned = doc.lower().translate(
            str.maketrans('', '', string.punctuation)
        )
        words = cleaned.split()
        vocab_set.update(words)

    return sorted(list(vocab_set))


def vectorize_text(text, vocabulary):
    '''
    Converts a single text document into a numerical vector.
    '''
    vector = [0] * len(vocabulary)

    cleaned = text.lower().translate(
        str.maketrans('', '', string.punctuation)
    )
    words = cleaned.split()

    for word in words:
        if word in vocabulary:
            idx = vocabulary.index(word)
            vector[idx] += 1

    return vector


