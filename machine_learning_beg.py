# Implement K-Fold Cross-Validation

import numpy as np

def k_fold_cross_validation(X: np.ndarray, y: np.ndarray, k=5, shuffle=True):
    '''
    Perform custom k-fold cross-validation split without using sklearn.

    Parameters:
        X (np.ndarray): Feature array.
        y (np.ndarray): Target/label array.
        k (int): Number of folds.
        shuffle (bool): Whether to shuffle the data before splitting.

    Returns:
        List[Tuple[List[int], List[int]]]: Each tuple contains (train_indices, test_indices).
    '''

    # Get number of samples
    n_samples = len(X)

    # Create indices
    indices = np.arange(n_samples)

    # Shuffle if required
    if shuffle:
        np.random.shuffle(indices)

    # Calculate fold sizes
    fold_sizes = np.full(k, n_samples // k, dtype=int)
    fold_sizes[:n_samples % k] += 1

    splits = []
    current = 0

    for fold_size in fold_sizes:
        start, stop = current, current + fold_size

        # Test indices for current fold
        test_indices = indices[start:stop]

        # Remaining indices are training indices
        train_indices = np.concatenate(
            (indices[:start], indices[stop:])
        )

        splits.append(
            (train_indices.tolist(), test_indices.tolist())
        )

        current = stop

    return splits


