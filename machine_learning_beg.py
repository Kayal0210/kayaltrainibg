# Calculate F-Score for Evaluating Binary Classifier

import numpy as np

def f_score(y_true, y_pred, beta):
    '''
    Calculate F-Score for a binary classification task.

    Args:
        y_true (np.ndarray): True binary labels.
        y_pred (np.ndarray): Predicted binary labels.
        beta (float): Weight factor for recall.

    Returns:
        float: F-Score rounded to 3 decimal places.
    '''

    # Count True Positives (TP)
    TP = np.sum((y_true == 1) & (y_pred == 1))

    # Count False Positives (FP)
    FP = np.sum((y_true == 0) & (y_pred == 1))

    # Count False Negatives (FN)
    FN = np.sum((y_true == 1) & (y_pred == 0))

    # Avoid division by zero
    if TP + FP == 0:
        precision = 0
    else:
        precision = TP / (TP + FP)

    if TP + FN == 0:
        recall = 0
    else:
        recall = TP / (TP + FN)

    # Avoid division by zero in F-score formula
    if (beta**2 * precision + recall) == 0:
        return 0.0

    # Calculate F-Score
    f_beta = ((1 + beta**2) * precision * recall) / ((beta**2 * precision) + recall)

    return round(f_beta, 3)


